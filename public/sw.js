/* ---------------------------------------------------------------------------
 * Service Worker بسيط جداً — بلا أي تخزين مؤقت (no caching).
 *
 * الهدف الوحيد: استيفاء شرط «قابلية التثبيت» في Chrome/Android حتى يستطيع
 * المستخدم تثبيت «واصل شات» كتطبيق من الشاشة الرئيسية.
 *
 * مهم جداً:
 *  - لا نُخزّن أي طلب في الكاش ولا نُعيد أي استجابة محفوظة مسبقاً.
 *  - مستمع fetch فارغ ⇒ المتصفح يجلب كل شيء من الشبكة كما هو دائماً.
 *  لذلك لا يمكن أن يظهر للمستخدم إصدار قديم، ولا تحدث أي حلقة إعادة تحميل.
 * ------------------------------------------------------------------------- */

self.addEventListener('install', () => {
  // تفعيل النسخة الجديدة فوراً بدل انتظار إغلاق كل التبويبات
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  // السيطرة على التبويبات المفتوحة حالاً حتى يُحتسب الشرط فوراً
  event.waitUntil(self.clients.claim())
})

// مستمع فارغ: لا اعتراض ولا تخزين — السلوك الافتراضي (الشبكة) تماماً
self.addEventListener('fetch', () => {})
